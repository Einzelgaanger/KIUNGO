import { mkdirSync, writeFileSync } from "fs";
import path from "path";

/** Minimal valid JPEG (1×1) with a COM marker so each file hashes differently. */
function jpegWithComment(comment: string): Buffer {
  const jfif = Buffer.from([
    0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01,
    0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00,
  ]);
  const commentBytes = Buffer.from(comment, "utf8");
  const com = Buffer.alloc(4 + commentBytes.length);
  com[0] = 0xff;
  com[1] = 0xfe;
  com.writeUInt16BE(2 + commentBytes.length, 2);
  commentBytes.copy(com, 4);
  const rest = Buffer.from([
    0xff, 0xdb, 0x00, 0x43, 0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08,
    0x07, 0x07, 0x07, 0x09, 0x09, 0x08, 0x0a, 0x0c, 0x14, 0x0d, 0x0c, 0x0b,
    0x0b, 0x0c, 0x19, 0x12, 0x13, 0x0f, 0x14, 0x1d, 0x1a, 0x1f, 0x1e, 0x1d,
    0x1a, 0x1c, 0x1c, 0x20, 0x24, 0x2e, 0x27, 0x20, 0x22, 0x2c, 0x23, 0x1c,
    0x1c, 0x28, 0x37, 0x29, 0x2c, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1f, 0x27,
    0x39, 0x3d, 0x38, 0x32, 0x3c, 0x2e, 0x33, 0x34, 0x32, 0xff, 0xc0, 0x00,
    0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xff, 0xc4,
    0x00, 0x14, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03, 0xff, 0xda, 0x00, 0x08,
    0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x7f, 0xff, 0xd9,
  ]);
  return Buffer.concat([jfif, com, rest]);
}

export function writeMockPhotos(root = process.cwd()): string[] {
  const dir = path.join(root, "public", "mock");
  mkdirSync(dir, { recursive: true });
  const urls: string[] = [];
  for (let i = 1; i <= 24; i += 1) {
    const name = `delivery-${String(i).padStart(2, "0")}.jpg`;
    writeFileSync(path.join(dir, name), jpegWithComment(`kiungo-delivery-${i}`));
    urls.push(`/mock/${name}`);
  }
  return urls;
}
